#!/usr/bin/env node
// Regenerates src/htmlContent.ts from the standalone flow map page
// (~/workspace/42-flowmap/index.html — the single source of truth for the
// page, including its embedded data snapshot and touch/validator UI).
// Run `node build-data.mjs` in ../42-flowmap first if you want fresh data.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const srcPath = join(dir, '..', '..', '42-flowmap', 'index.html');
const outPath = join(dir, '..', 'src', 'htmlContent.ts');

const html = await readFile(srcPath, 'utf8');
await mkdir(dirname(outPath), { recursive: true });
await writeFile(
  outPath,
  '// GENERATED by scripts/sync-html.mjs from ../42-flowmap/index.html — do not edit by hand.\n' +
    'export const HTML_CONTENT: string = ' +
    JSON.stringify(html) +
    ';\n',
);
console.log(`htmlContent.ts written from ${srcPath} (${html.length} chars)`);
